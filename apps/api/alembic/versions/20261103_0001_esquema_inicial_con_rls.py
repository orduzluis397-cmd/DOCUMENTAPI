# NULLIF: fuera de una transacción con contexto, current_setting devuelve '' (o NULL si nunca se
# fijó), y ''::uuid fallaría. Con NULL la comparación es desconocida y la fila no se ve.
CURRENT_ORG = "NULLIF(current_setting('app.organization_id', true), '')::uuid"


def _app_role() -> str:
    role = os.environ.get("POSTGRES_APP_USER", "contable_app")
    if not role.replace("_", "").isalnum():
        raise ValueError(f"Nombre de rol inválido: {role!r}")
    return role


def _enable_security() -> None:
    for table in ALL_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        # FORCE: la política aplica también al dueño de la tabla (salvo superusuarios).
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")

    op.execute(
        "CREATE POLICY tenant_isolation ON organizations "
        f"USING (id = {CURRENT_ORG}) WITH CHECK (id = {CURRENT_ORG})"
    )
    for table in TENANT_TABLES:
        if table == "audit_events":
            continue
        op.execute(
            f"CREATE POLICY tenant_isolation ON {table} "
            f"USING (organization_id = {CURRENT_ORG}) "
            f"WITH CHECK (organization_id = {CURRENT_ORG})"
        )
    # Auditoría: solo leer e insertar dentro de la organización; ninguna política de UPDATE/DELETE.
    op.execute(
        "CREATE POLICY tenant_select ON audit_events FOR SELECT "
        f"USING (organization_id = {CURRENT_ORG})"
    )
    op.execute(
        "CREATE POLICY tenant_insert ON audit_events FOR INSERT "
        f"WITH CHECK (organization_id = {CURRENT_ORG})"
    )

    # Inmutabilidad para cualquier rol (también el dueño): defensa en profundidad.
    op.execute(
        """
        CREATE FUNCTION audit_events_reject_change() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
          RAISE EXCEPTION 'audit_events es inmutable: % no permitido', TG_OP
            USING ERRCODE = 'insufficient_privilege';
        END;
        $$
        """
    )
    op.execute(
        "CREATE TRIGGER audit_events_immutable BEFORE UPDATE OR DELETE ON audit_events "
        "FOR EACH ROW EXECUTE FUNCTION audit_events_reject_change()"
    )

